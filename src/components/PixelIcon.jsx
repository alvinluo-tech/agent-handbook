export default function PixelIcon({ name, size = 16, style }) {
  const rects = P[name]
  if (!rects) return null
  return (
    <svg viewBox="0 0 16 16" width={size} height={size} shapeRendering="crispEdges" aria-hidden="true" style={{ display: 'inline-block', verticalAlign: '-3px', ...style }}>
      {rects.map(([x, y, w, h], i) => <rect key={i} x={x} y={y} width={w} height={h} fill="currentColor" />)}
    </svg>
  )
}
